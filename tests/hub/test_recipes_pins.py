"""Pins that must hold on the base too: S13g1 F1, and that old logs fold unchanged.

This module imports only APIs that exist on the base dev SHA, so the fail-before run can execute
it there. Both tests pass on the base (they pin existing behaviour S13g2 must not break).
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
from write_support import AGENT, Hub, brief_data, make_hub

from aar.hub.events import Actor, EventLog
from aar.hub.graph import WorkGraph
from aar.hub.writes import WriteError, create_brief, set_own_status

FIXTURE = Path(__file__).parent / "fixtures" / "graph_pre_s13g2.json"


@pytest.fixture
def hub(tmp_path: Any) -> Iterator[Hub]:
    made = make_hub(tmp_path)
    yield made
    made.log.close()


def test_s13g1_f1_set_own_status_key_reused_for_two_nodes_conflicts(hub: Hub) -> None:
    """S13g1 F1: one set_own_status idempotency key for two different nodes -> conflict."""
    a = create_brief(hub.log, brief_data(hub.project_id), AGENT, idempotency_key="a").body["node"]
    b = create_brief(
        hub.log, brief_data(hub.project_id, show="Other"), AGENT, idempotency_key="b"
    ).body["node"]
    set_own_status(hub.log, hub.project_id, a["id"], "active", AGENT, idempotency_key="k")
    with pytest.raises(WriteError) as excinfo:
        set_own_status(hub.log, hub.project_id, b["id"], "active", AGENT, idempotency_key="k")
    assert excinfo.value.code == "idempotency_conflict"
    # The second node did not move.
    assert WorkGraph(hub.log, hub.project_id).node(b["id"]).status == "pending"


def _strip_event_ids(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    # Skipped-event ids are minted by the log on append; compare everything else.
    return [{k: v for k, v in row.items() if k != "event_id"} for row in rows]


def test_old_log_folds_to_the_same_state(tmp_path: Path) -> None:
    """A log of pre-S13g2 event types folds to exactly the state the old code produced.

    The fixture (events plus the base-folded state) was generated by
    aar-evidence/s13g2/gen_pre_s13g2.py on the base dev SHA, before S13g2 added the recipe.*
    events and the aar.step/1 op schema. It guards graph folding against S13g2's changes.
    """
    fixture = json.loads(FIXTURE.read_text())
    log = EventLog(tmp_path / "replay.db")
    try:
        for event in fixture["events"]:
            log.append(
                event["type"], Actor(*event["actor"]), event["payload"],
                project_id=event["project_id"], ts=event["ts"],
            )
        graph = WorkGraph(log, fixture["project_id"])
        snap = graph.snapshot()
        got = {
            **graph.to_dict(),
            "skipped": [s.to_dict() for s in graph.skipped()],
            "creators": {k: [v.kind, v.id] for k, v in snap.creators.items()},
            "last_change": {
                k: [seq, actor.kind, actor.id, to]
                for k, (seq, actor, to) in snap.last_change.items()
            },
        }
    finally:
        log.close()
    expected = fixture["expected"]
    got["skipped"] = _strip_event_ids(got["skipped"])
    expected["skipped"] = _strip_event_ids(expected["skipped"])
    assert got == expected
